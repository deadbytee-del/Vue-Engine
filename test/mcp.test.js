const assert=require('assert')
const fs=require('fs')
const os=require('os')
const path=require('path')
const http=require('http')
const {PassThrough}=require('stream')
const M=require('../src/mcp.js')
let ts=null
try{ts=require('typescript')}catch(e){}
const root=fs.mkdtempSync(path.join(os.tmpdir(),'vue-mcp-'))
const other=fs.mkdtempSync(path.join(os.tmpdir(),'vue-out-'))
fs.writeFileSync(path.join(other,'secret.png'),'x')
fs.writeFileSync(path.join(root,'pic.png'),Buffer.from('89504e470d0a1a0a','hex'))
const logs=[]
const bridge={call:async(n,a)=>{logs.push(n);if(n==='screenshot')return Buffer.from('png').toString('base64');if(n==='logs')return['hello'];return{ok:true}}}
const srv=M.create({roots:[root],importRoots:[root],ts,bridge,runtimeSource:()=>'window.VueRuntime=window.VueRuntime||{Game:function(){}}',threeSource:()=>''})
let n=0
const rpc=async(method,params)=>srv.handle({jsonrpc:'2.0',id:++n,method,params})
const call=async(name,args)=>{const r=await rpc('tools/call',{name,arguments:args});return r}
const data=r=>JSON.parse(r.result.content[0].text)
;(async()=>{
let r=await rpc('initialize',{protocolVersion:'2025-03-26',capabilities:{},clientInfo:{name:'t',version:'1'}})
assert.strictEqual(r.result.serverInfo.name,'vue-engine')
assert.strictEqual(await srv.handle({jsonrpc:'2.0',method:'notifications/initialized'}),null)
r=await rpc('tools/list')
const names=r.result.tools.map(t=>t.name)
for(const x of['list_projects','open_project','new_project','save','get_scene','list_objects','get_object','create_object','update_object','delete_object','add_component','set_property','list_assets','import_asset','get_script','set_script','validate_script','run','stop','get_console_logs','screenshot','list_extensions','install_extension','export_html'])assert.ok(names.includes(x),'tool '+x)
assert.ok(r.result.tools.every(t=>t.inputSchema&&t.inputSchema.type==='object'&&t.description))
r=await rpc('resources/list')
assert.deepStrictEqual(r.result.resources.map(x=>x.uri).sort(),['vue://api','vue://behaviors','vue://project','vue://templates'])
r=await rpc('resources/read',{uri:'vue://api'})
assert.ok(r.result.contents[0].text.includes('declare interface Vue'))
r=await rpc('resources/read',{uri:'vue://templates'})
assert.ok(JSON.parse(r.result.contents[0].text).length>3)
r=await call('get_scene',{})
assert.ok(r.result.isError&&/No project is open/.test(r.result.content[0].text))
r=await call('new_project',{name:'Test Game',mode:'2d'})
assert.ok(data(r).path.startsWith(fs.realpathSync(root)))
r=await call('new_project',{name:'../escape'})
assert.ok(!fs.existsSync(path.join(root,'..','escape.vue')))
r=await call('open_project',{path:path.join(other,'x.vue')})
assert.ok(r.result.isError&&/outside/.test(r.result.content[0].text))
r=await call('open_project',{path:path.join(root,'..','..','etc','passwd')})
assert.ok(r.result.isError)
r=await call('create_object',{kind:'rect',properties:{name:'Box',x:10,y:20,w:30,h:30,body:'dynamic',tags:['crate']}})
const id=data(r).id
assert.strictEqual(data(await call('get_object',{id:'Box'})).x,10)
r=await call('set_property',{id,key:'color',value:'#ff0000'})
assert.strictEqual(data(r).color,'#ff0000')
r=await call('set_property',{id,key:'__proto__',value:1})
assert.ok(r.result.isError)
r=await call('set_property',{id,key:'x',value:'far'})
assert.ok(r.result.isError)
r=await call('create_object',{kind:'rect',bogus:1})
assert.ok(r.result.isError&&/Unknown field/.test(r.result.content[0].text))
r=await call('add_component',{id,preset:'Health',options:{max:50}})
assert.deepStrictEqual(data(r).behaviors,['Health'])
assert.strictEqual(data(await call('get_object',{id})).beh[0].max,50)
r=await call('add_component',{id,preset:'Nope'})
assert.ok(r.result.isError)
r=await call('add_component',{id,preset:'Player:Platformer'})
assert.ok(data(r).player)
r=await call('set_script',{id,mode:'events',events:{rows:[{k:'event',ev:{t:'start',v:{}},conds:[],acts:[{t:'say',v:{text:'Hi',sec:1}}],subs:[]}]}})
assert.strictEqual(data(r).mode,'events')
r=await call('validate_script',{id})
assert.ok(data(r).ok)
r=await call('set_script',{id,mode:'events',events:{nope:1}})
assert.ok(r.result.isError)
if(ts){
r=await call('validate_script',{code:'export function update(dt:number){ self.x += "a" }'})
assert.ok(!data(r).ok&&data(r).diagnostics[0].message.length>5,'type error reported')
r=await call('validate_script',{code:'export function update(dt:number){ self.x += dt; vue.behavior(self,"Health",{max:3}) }'})
assert.ok(data(r).ok,JSON.stringify(data(r)))
}
r=await call('set_script',{id,mode:'code',code:'export function start(){ vue.log("hi") }'})
assert.strictEqual(data(r).mode,'code')
r=await call('import_asset',{path:path.join(root,'pic.png')})
assert.strictEqual(data(r).type,'image')
r=await call('import_asset',{path:path.join(other,'secret.png')})
assert.ok(r.result.isError&&/outside/.test(r.result.content[0].text))
assert.ok(data(await call('list_assets',{})).some(a=>a.name==='pic.png'))
r=await call('install_extension',{id:'fx'})
const exts=data(await call('list_extensions',{}))
assert.ok(exts.length>5)
r=await call('delete_object',{id})
assert.strictEqual(data(r).deleted,1)
r=await call('save',{})
assert.ok(fs.existsSync(data(r).path))
assert.ok(JSON.parse(fs.readFileSync(data(r).path,'utf8')).assets['pic.png'])
if(ts){
r=await call('export_html',{path:path.join(root,'out.html')})
assert.ok(fs.existsSync(path.join(root,'out.html')))
}
r=await call('export_html',{path:path.join(other,'out.html')})
assert.ok(r.result.isError)
r=await call('screenshot',{})
assert.strictEqual(r.result.content[0].type,'image')
assert.deepStrictEqual(data(await call('get_console_logs',{limit:5})),['hello'])
assert.ok(logs.includes('run')===false)
await new Promise(r=>setTimeout(r,2200))
await call('run',{})
assert.ok(logs.includes('run'))
await new Promise(r=>setTimeout(r,2200))
r=await rpc('nope')
assert.strictEqual(r.error.code,-32601)
let limited=0
for(let i=0;i<80;i++){const q=await rpc('ping');if(q.error&&q.error.code===-32000)limited++}
assert.ok(limited>0,'rate limit')
await new Promise(r=>setTimeout(r,2200))
const srv2=M.create({roots:[root],ts})
const h=await M.startHttp(srv2,{})
const post=(token,body,host)=>new Promise(res=>{const q=http.request({host:'127.0.0.1',port:h.port,path:'/mcp',method:'POST',headers:Object.assign({'Content-Type':'application/json'},token?{Authorization:'Bearer '+token}:{},host?{Host:host}:{})},s=>{let b='';s.on('data',c=>b+=c);s.on('end',()=>res({status:s.statusCode,body:b}))});q.end(JSON.stringify(body))})
let q=await post(null,{jsonrpc:'2.0',id:1,method:'ping'})
assert.strictEqual(q.status,401)
q=await post('wrong',{jsonrpc:'2.0',id:1,method:'ping'})
assert.strictEqual(q.status,401)
q=await post(h.token,{jsonrpc:'2.0',id:1,method:'ping'},'evil.example')
assert.strictEqual(q.status,403)
q=await post(h.token,{jsonrpc:'2.0',id:1,method:'tools/list'})
assert.strictEqual(q.status,200)
assert.ok(JSON.parse(q.body).result.tools.length>20)
await h.close()
const inp=new PassThrough(),out=new PassThrough()
M.runStdio(M.create({roots:[root]}),inp,out)
const got=await new Promise(res=>{out.once('data',d=>res(JSON.parse(String(d))));inp.write(JSON.stringify({jsonrpc:'2.0',id:9,method:'ping'})+'\n')})
assert.strictEqual(got.id,9)
fs.rmSync(root,{recursive:true,force:true})
fs.rmSync(other,{recursive:true,force:true})
console.log('mcp tests passed ('+names.length+' tools)')
})().catch(e=>{console.error(e);process.exit(1)})
