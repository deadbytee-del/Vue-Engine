const assert=require('assert')
require('../src/mesh.js')
const M=VueMesh
const closed=(m,n)=>{const c=M.check(m);assert(c.ok&&c.closed,(n||'')+' not a closed manifold '+JSON.stringify(c))}
for(const k of Object.keys(M.PRIMS)){
const m=M.primitive(k)
assert(m.f.length>0,k)
const c=M.check(m)
assert(c.ok,k+' invalid '+JSON.stringify(c))
if(!['plane','grid','circle'].includes(k)){closed(m,k);assert(M.volume(m)>0,k+' inverted volume '+M.volume(m))}
}
let c=M.primitive('cube')
assert.strictEqual(M.stats(c).faces,6)
const top=c.f.findIndex(f=>M.fn(c,f)[1]>0.9)
let m=M.clone(c)
let r=M.extrudeFaces(m,[top],0.5)
closed(m,'extrude');assert.strictEqual(m.f.length,10)
assert(M.volume(m)>M.volume(c))
m=M.clone(c);r=M.insetFaces(m,[top],0.3);closed(m,'inset');assert.strictEqual(m.f.length,10)
m=M.clone(c);r=M.insetAbs(m,[top],0.1,0);closed(m,'insetAbs')
m=M.clone(c);const es=[...M.edgeMap(m).keys()]
M.bevel(m,es,0.1);closed(m,'bevel');assert(M.volume(m)<M.volume(c));assert(m.f.length>6)
m=M.clone(c);const e0=[...M.edgeMap(m).values()][0]
r=M.loopCut(m,e0.f[0],e0.a,e0.b,1,0.5)
closed(m,'loopcut');assert.strictEqual(m.f.length,10);assert(Math.abs(M.volume(m)-M.volume(c))<1e-9)
m=M.clone(c);r=M.loopCut(m,e0.f[0],e0.a,e0.b,3);closed(m,'loopcut3');assert.strictEqual(m.f.length,18)
m=M.clone(c);M.subdivideFaces(m);closed(m,'subdiv');assert.strictEqual(m.f.length,24)
m=M.subsurf(c,2);closed(m,'subsurf');assert.strictEqual(m.f.length,96);assert(M.volume(m)<M.volume(c)&&M.volume(m)>0.3)
let pl=M.primitive('plane')
m=M.solidify(pl,0.2,-1);closed(m,'solidify');assert(M.volume(m)>0)
let half=M.primitive('cube');half=M.clone(half);M.xform(half,p=>[p[0]+0.5,p[1],p[2]])
const mir=M.mirror(half,0);closed(mir,'mirror');assert.strictEqual(M.stats(mir).faces,10)
const arr=M.arrayMod(c,3,[2,0,0],[0,0,0],0);assert.strictEqual(arr.f.length,18)
const b2=M.clone(c);M.xform(b2,p=>[p[0]+0.4,p[1]+0.4,p[2]+0.4])
const un=M.boolean(c,b2,'union'),df=M.boolean(c,b2,'difference'),it=M.boolean(c,b2,'intersect')
assert(Math.abs(M.volume(un)-(1+1-0.6*0.6*0.6))<1e-3,'union vol '+M.volume(un))
assert(Math.abs(M.volume(df)-(1-0.216))<1e-3,'diff vol '+M.volume(df))
assert(Math.abs(M.volume(it)-0.216)<1e-3,'int vol '+M.volume(it))
m=M.clone(c);r=M.deleteFaces(m,[top]);assert.strictEqual(m.f.length,5);assert(!M.check(m).closed)
m=M.clone(c);const ee=[...M.edgeMap(m).values()].find(e=>e.f.length===2);M.dissolveEdges(m,[M.K(ee.a,ee.b)]);assert.strictEqual(m.f.length,5)
m=M.clone(c);M.mergeVerts(m,[0,1],'center');assert.strictEqual(m.v.length,7)
m=M.clone(c);m.f[0]=m.f[0].slice().reverse();M.recalc(m);closed(m,'recalc');assert(M.volume(m)>0)
m=M.clone(c);M.flip(m);assert(M.volume(m)<0)
m=M.clone(c);M.triangulate(m);assert.strictEqual(m.f.length,12);closed(m,'tri')
m=M.primitive('sphere',{seg:24});const dm=M.decimate(m,0.5);assert(dm.f.length<m.f.length*0.7);assert(M.check(dm).ok)
m=M.clone(c);r=M.connect(m,m.f[0][0],m.f[0][2]);assert.strictEqual(m.f.length,7)
m=M.clone(c);r=M.extrudeFaces(m,[top],0);const sel=r.f;assert.strictEqual(sel.length,1)
const g=M.groups(M.primitive('cylinder'));assert(g.length===1&&g[0].pos.length>0)
const o=M.fromOBJ(M.toOBJ(M.primitive('sphere')));closed(o,'obj')
const lp=M.edgeLoop(M.primitive('cylinder',{seg:8}),[...M.edgeMap(M.primitive('cylinder',{seg:8})).keys()][0]);assert(lp.length>=1)
const san=M.sanitize(c);assert.strictEqual(san.f.length,6)
assert.throws(()=>M.sanitize({v:[[0,0,0]],f:[[0,1,2]]}))
const cyl=M.primitive('cylinder',{seg:8});const rg=M.ringEdges(cyl,0,cyl.f[0][0],cyl.f[0][1]);assert(Array.isArray(rg))
const big=M.primitive('icosphere',{sub:4});const t0=Date.now();const rn=M.render(big);assert(Date.now()-t0<2000);assert.strictEqual(rn.count,big.f.length)
console.log('mesh tests passed')
const MD=require('../src/model3d.js')
const sp=MD.validate({parts:[{type:'mesh',name:'m',mesh:M.clone(c),mods:[{type:'mirror',axis:0},{type:'subsurf',level:1}]},{type:'box',size:[1,1,1],pos:[3,0,0]}]})
const bk=MD.bake(sp);assert.strictEqual(bk.meshes.length,2);assert(bk.tris>20)
const glb=MD.toGLB(sp);const back=M.fromGLB(glb);assert(back.f.length>0)
assert.throws(()=>MD.validate({parts:[{type:'mesh',mesh:{v:[],f:[[0,1,2]]}}]}))
const fm=M.fromTris(MD.bake({parts:[{type:'box',size:[1,1,1]}]}).meshes);closed(fm,'fromTris')
console.log('mesh model tests passed')
